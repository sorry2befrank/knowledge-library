// Generate the producer's specification identity from the reviewed repository copy at build time.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const text = readFileSync(new URL("../docs/DESIGN.md", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const revision = /^revision:\s*([0-9.]+)\s*$/m.exec(text)?.[1];
const status = /Status:\s*(FINAL|DRAFT)\s+r[0-9.]+/i.exec(text)?.[1]?.toUpperCase();
if (!revision || !status) throw new Error("Repository DESIGN is missing its revision or publication status");
const spec = { revision: `r${revision}`, hash: createHash("sha256").update(text).digest("hex"), status };
const output = new URL("../packages/core/src/evidence/design-spec.generated.ts", import.meta.url);
writeFileSync(output, `// Generated by scripts/build-spec.ts; do not edit.\nexport const BUILD_DESIGN_SPEC = Object.freeze(${JSON.stringify(spec)});\n`);
console.log(`build-spec: ${spec.revision} ${spec.status}`);
