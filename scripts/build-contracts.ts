// Compile JSON Schema before deployment: Workers disallow Ajv's new Function at runtime.
// Standalone output retains the exact Ajv options/formats used by the Node validator.
import { writeFileSync } from 'node:fs';
import { Ajv2020 } from 'ajv/dist/2020.js';
import * as formatsModule from 'ajv-formats';
import * as standaloneModule from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { SCHEMAS } from '../packages/contracts/src/schemas.ts';
import { TOOL_DEFINITIONS } from '../packages/core/src/tools/definitions.ts';

const addFormats = (formatsModule as unknown as { default: (ajv: Ajv2020) => void }).default;
const standalone = (standaloneModule as unknown as { default: (ajv: Ajv2020, names: Record<string, string>) => string }).default;
const ajv = new Ajv2020({ allErrors: true, strict: true, strictTypes: false, strictRequired: false,
  allowUnionTypes: true, code: { source: true, esm: true } });
addFormats(ajv);
const names: Record<string, string> = {};
const schemas: string[] = [], inputs: string[] = [];
for (const schema of Object.values(SCHEMAS)) {
  const name = `v${Object.keys(names).length}`;
  ajv.addSchema(schema); names[name] = schema.$id;
  schemas.push(`${JSON.stringify(schema.$id)}: ${name}`);
}
for (const tool of TOOL_DEFINITIONS) {
  const name = `v${Object.keys(names).length}`, id = `kl-input:${tool.name}`;
  ajv.addSchema(tool.inputSchema, id); names[name] = id;
  inputs.push(`${JSON.stringify(JSON.stringify(tool.inputSchema))}: ${name}`);
}
const source = standalone(ajv, names) + '\nexport const schemaValidators = {' + schemas.join(',') + '};'
  + '\nexport const inputValidators = {' + inputs.join(',') + '};\n';
// Bundle Ajv's small format/Unicode helper imports now as well. The runtime receives no compiler.
const compiled = await build({ stdin: { contents: source, resolveDir: process.cwd(), loader: 'js' },
  bundle: true, write: false, platform: 'browser', format: 'esm', target: 'es2022' });
writeFileSync(new URL('../packages/contracts/src/validators.generated.ts', import.meta.url),
  '// @ts-nocheck\n// Generated by scripts/build-contracts.ts; do not edit.\n' + compiled.outputFiles![0]!.text);
console.log(`build-contracts: ${schemas.length} schemas, ${inputs.length} tool inputs (standalone)`);
