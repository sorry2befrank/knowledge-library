// Writes the signed-wrapper fixtures that REALLY verify (S1c D8): a test key (never a production key), the public key in
// trust.json, a valid wrapper over the positive envelope, a tampered one (bytes edited, digest recomputed, signature stale)
// and a key-mismatch one (signed correctly, but the envelope names another producer key). Run: node scripts/signed-evidence-fixtures.ts
import { readFileSync, writeFileSync } from "node:fs";
import { generateServiceKey, ed25519Signer, toBase64Url, sha256Hex } from "@kl/core";

const DIR = "schemas/fixtures/library-evidence-signed/v1";
const envelope = JSON.parse(readFileSync("schemas/fixtures/library-evidence/v1/positive.json", "utf8")) as Record<string, unknown>;
const k = await generateServiceKey();
const signer = await ed25519Signer(k.privateKey, k.keyId);
async function wrap(env: Record<string, unknown>, keyId = k.keyId) {
  const bytes = JSON.stringify(env);
  return { schemaVersion: "library-evidence-signed/v1", envelopeBytes: bytes, digest: sha256Hex(bytes), sig: toBase64Url(await signer.sign(new TextEncoder().encode(bytes))), keyId };
}
const good = await wrap({ ...envelope, producer: { ...(envelope.producer as object), keyId: k.keyId } });
const tamperedBytes = good.envelopeBytes.replace('"notesHeld":0', '"notesHeld":99');
const tampered = { ...good, envelopeBytes: tamperedBytes, digest: sha256Hex(tamperedBytes) }; // digest fixed up, signature stale
const mismatch = await wrap({ ...envelope, producer: { ...(envelope.producer as object), keyId: "k-someone-else" } }); // signed by our key, envelope names another
writeFileSync(`${DIR}/trust.json`, JSON.stringify({ note: "a TEST key generated by scripts/signed-evidence-fixtures.ts; never a production key", keyId: k.keyId, publicKeyB64: k.publicKeyB64 }, null, 2) + "\n");
writeFileSync(`${DIR}/valid-signed.json`, JSON.stringify(good, null, 2) + "\n");
writeFileSync(`${DIR}/tampered-signed.json`, JSON.stringify(tampered, null, 2) + "\n");
writeFileSync(`${DIR}/key-mismatch-signed.json`, JSON.stringify(mismatch, null, 2) + "\n");
console.log(`signed fixtures written with key ${k.keyId}`);
