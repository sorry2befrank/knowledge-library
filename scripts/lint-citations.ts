// Lint: no kl: citation in the repo that fixtures/gen.ts did not generate (DESIGN §12.2 connector rule).
// Exempt: docs/ (planning text owned by Frank/Codex), node_modules, and two placeholder noteIds used in
// tests: 0000000000 (never minted: '0' x10 is a valid pattern but gen never produces it by construction
// here, see check below) and 7QK2M9X4AB (DESIGN's own worked example).
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { generateFixtures } from "../fixtures/gen.ts";

const PLACEHOLDERS = new Set(["0000000000", "7QK2M9X4AB"]);
const fx = generateFixtures();
const generated = new Set(fx.notes.map((n) => n.noteId));
if (generated.has("0000000000") || generated.has("7QK2M9X4AB")) { console.error("placeholder collides with a generated id"); process.exit(1); }

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    if (e === "node_modules" || e === ".git" || e === "docs" || e === "out") continue;
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|md|json|yml|yaml|mjs|js|txt)$/.test(e)) out.push(p);
  }
  return out;
}
let bad = 0;
for (const f of walk(".")) {
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(/kl:([0-9A-HJKMNP-TV-Z]{10})@\d+/g)) {
    if (!generated.has(m[1]!) && !PLACEHOLDERS.has(m[1]!)) { console.error(`${f}: citation ${m[0]} was not generated by fixtures/gen.ts`); bad++; }
  }
}
if (bad) { console.error(`lint-citations: ${bad} violation(s)`); process.exit(1); }
console.log(`lint-citations: ok (${generated.size} generated ids, ${PLACEHOLDERS.size} placeholders)`);
