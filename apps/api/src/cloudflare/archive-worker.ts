// Binding structure is generated by pinned Wrangler. The owner selects mode at packaging.
type ConfigBindings='RUNTIME_MODE'|'RUNTIME_CONFIG_COUNT'|`RUNTIME_CONFIG_${1|2|3|4|5|6|7|8}`;
type Env=Omit<CloudArchiveEnv,ConfigBindings>&Record<ConfigBindings,string>;
// Pilot memory bound: one materialized upload at a time, before the serial queue.
const MAX_PENDING=1;
function routeLimit(req:{url:string;method:string}):number|undefined {
  const u=new URL(req.url);if(u.search)return undefined;
  if(req.method==='POST'){
    if(u.pathname==='/v1/runtime/release')return 8192;
    if(u.pathname==='/v1/enroll')return 32*1024;
    if(u.pathname==='/v1/commit')return 4096;
    if(['/v1/manifest/diff','/v1/batch'].includes(u.pathname))return 4*1024*1024;
    if(['/mcp','/v1/save'].includes(u.pathname))return 2*1024*1024;
  }
  if(req.method==='PUT'&&/^\/v1\/upload\/[^/]+\/\d+$/.test(u.pathname))return 4*1024*1024;
  if(req.method==='GET'&&(['/health','/v1/runtime/release','/v1/status'].includes(u.pathname)||/^\/v1\/version\/[^/]+\/bytes$/.test(u.pathname)))return 0;
  if(req.method==='HEAD'&&u.pathname==='/health')return 0;
  return undefined;
}
function allowed(req:{url:string;method:string},config:RuntimeConfig):boolean {
  return new URL(req.url).origin===config.audience.origin&&routeLimit(req)!==undefined;
}
function runtimeConfig(env:Env):RuntimeConfig|undefined {
  if(!['active','closed'].includes(env.RUNTIME_MODE))return undefined;
  try{return readRuntimeConfig(env);}catch{return undefined;}
}
function toRequest(request:WorkerRequest):Request{
  const init:RequestInit&{duplex?:'half'}={method:request.method,headers:Object.fromEntries(request.headers),body:request.body as ReadableStream<Uint8Array>|null};
  if(request.body)init.duplex='half';
  return new Request(request.url,init);
}

export class LibraryDO extends DurableObject<Env> {
  private readonly safety:RuntimeSafety;
  private readonly config:RuntimeConfig|undefined;
  private ready:Promise<void>|undefined;
  private safetyReady:Promise<void>|undefined;
  private tail:Promise<void>=Promise.resolve();
  private api:((req:Request)=>Promise<Response>)|undefined;
  private scheduler:OutboxScheduler|undefined;
  private catalog:Catalog|undefined;
  private seal:(()=>Promise<unknown>)|undefined;
  private verify:(()=>Promise<void>)|undefined;
  private retryOnly=false;
  private pending=0;
  private statusPending=0;
  constructor(ctx:DurableObjectState,env:Env){
    super(ctx,env);this.config=runtimeConfig(env);
    this.safety=new RuntimeSafety({get:key=>ctx.storage.get(key),put:(key,value)=>ctx.storage.put(key,value),delete:key=>ctx.storage.delete(key),sync:()=>ctx.storage.sync(),
      abort:reason=>ctx.abort(reason),waitUntil:promise=>ctx.waitUntil(promise)});
  }
  private async initialize():Promise<void>{
    const config=this.config;if(!config)throw Error('archive-unavailable');
    this.safety.check();
    const policy={...config.policy,publicKey:await importPublicKey(config.policy.publicKeyB64)};
    if(!(await verifyAcceptance(config.policyAcceptance,bundleHash(config.policyBundle),policy)).ok)throw Error('archive-unavailable');
    const rules=await loadReferenceAdmissionRules(config.policyBundle,config.policyAcceptance,policy);
    const store=this.safety.store(new R2ObjectStore(boundedArchiveBucket(this.env.ARCHIVE),100));
    // Only schema/local projection construction runs under the DO input gate.
    await this.ctx.blockConcurrencyWhile(async()=>{
      this.catalog=new Catalog({db:this.safety.sql(openDurableSql(this.ctx.storage)),blobStore:store,mirror:store,denyRules:rules});
    });
    const catalog=this.catalog!;
    const durability={store,libraryId:config.audience.libraryId,minPolicyEpoch:config.policy.minEpoch,maxSnapshotBytes:16*1024*1024};
    this.verify=()=>verifyArchiveFreshness(catalog,durability);
    this.seal=()=>sealArchive(catalog,durability);
    try{await this.verify();}catch{
      if(await canRetryUnsealedEnrollment(catalog,durability))this.retryOnly=true;
      else{
        // Restore only through the existing pristine-catalog guard and latest
        // locked evidence. A nonempty/stale projection is never cleared here.
        await restoreArchive(catalog,durability);
        await this.verify();
      }
    }
    this.api=createApiHandler({catalog,enrollmentTrust:{approval:config.approval,policy,audience:config.audience,now:()=>catalog.clock.now()}});
    this.scheduler=new OutboxScheduler({catalog:{db:catalog.db,dispatchOutbox:options=>this.safety.run(async()=>{
      await this.verify!();
      try{return await catalog.dispatchOutbox(options);}finally{await this.seal!();}
    },45_000)},alarms:{
      getAlarm:()=>this.safety.run(()=>this.ctx.storage.getAlarm()),
      setAlarm:at=>this.safety.run(()=>this.ctx.storage.setAlarm(at)),
      deleteAlarm:()=>this.safety.run(()=>this.ctx.storage.deleteAlarm()),
    }});
    if(!this.retryOnly){await this.seal();await this.scheduler.recover();}
  }
  private ensureReady():Promise<void>{
    return this.ready??=(this.safety.run(()=>this.initialize(),45_000).catch(()=>{this.ready=undefined;throw Error('archive-unavailable');}));
  }
  private loadSafety():Promise<void>{return this.safetyReady??=this.safety.load();}
  private serial<T>(effect:()=>Promise<T>):Promise<T>{
    const work=this.tail.then(effect);this.tail=work.then(()=>undefined,()=>undefined);return work;
  }
  private releaseTrust(){return {approval:this.config!.approval,audience:this.config!.audience,now:()=>new Date().toISOString()};}
  private releasePort():RuntimeReleasePort{return {proofs:this.safety.store(new R2ObjectStore(boundedArchiveBucket(this.env.ARCHIVE,8192),1)),get:key=>this.safety.run(()=>this.ctx.storage.get(key)),
    put:(key,value)=>this.safety.run(()=>this.ctx.storage.put(key,value)),sync:()=>this.safety.run(()=>this.ctx.storage.sync())};}
  private async released():Promise<boolean>{
    return this.env.RUNTIME_MODE==='active'&&runtimeIsReleased(this.releasePort(),this.releaseTrust(),this.env.VERSION?.id);
  }
  private async releaseRequest(request:Request):Promise<Response>{
    let input:unknown;try{input=await request.json();}catch{return Response.json({error:'runtime-release-refused'},{status:400});}
    if(this.env.RUNTIME_MODE==='closed'&&(input as {claims?:{mode?:unknown}}|null)?.claims?.mode!=='closed')return unavailable();
    const port=this.releasePort();let wrote=false;
    try{
      const state=await acceptRuntimeRelease(input,{...port,
        proofs:{...port.proofs,put:async(key,bytes,options)=>{wrote=true;return port.proofs.put(key,bytes,options);}},
        put:async(key,value)=>{wrote=true;await port.put(key,value);}},this.releaseTrust(),this.env.VERSION?.id);
      return Response.json(state,{headers:{'cache-control':'no-store'}});
    }catch{
      if(wrote)throw Error('archive-unavailable'); // retain pending intent after any uncertain write
      return Response.json({error:'runtime-release-refused'},{status:400,headers:{'cache-control':'no-store'}});
    }
  }
  override async fetch(request:WorkerRequest):Promise<WorkerResponse>{
    if(!this.config||!allowed(request,this.config))return unavailable() as WorkerResponse;
    const path=new URL(request.url).pathname;
    if((path==='/health'&&['GET','HEAD'].includes(request.method))||(path==='/v1/runtime/release'&&request.method==='GET')){
      if(this.statusPending>=1)return unavailable() as WorkerResponse;
      this.statusPending++;
      const status=(async()=>{
        // Only signed release metadata, never archive/client data. Read-only
        // status remains available during rollback and a safety hold.
        const release=await runtimeReleaseState({proofs:new R2ObjectStore(boundedArchiveBucket(this.env.ARCHIVE,8192),1),get:key=>this.ctx.storage.get(key),put:()=>{throw Error('read-only');},sync:async()=>{}},this.releaseTrust());
        const payload=path==='/health'?{phase:'archive-runtime',versionId:this.env.VERSION?.id??null,mode:this.env.RUNTIME_MODE,release}:release;
        return new Response(request.method==='HEAD'?null:JSON.stringify(payload),{headers:{'content-type':'application/json','cache-control':'no-store'}});
      })().catch(()=>unavailable()).finally(()=>{this.statusPending--;});
      this.ctx.waitUntil(status);return await responseDeadline(status,10_000) as WorkerResponse;
    }
    if(this.safety.held||this.pending>=MAX_PENDING||
      (this.env.RUNTIME_MODE!=='active'&&path!=='/v1/runtime/release'))return unavailable() as WorkerResponse;
    this.pending++;
    // A client response deadline never releases the internal serialized operation.
    const work=(async()=>{
      try{
        const buffered=await boundedRequest(toRequest(request),routeLimit(request)!);
        await this.loadSafety();this.safety.check();
        return await this.serial(()=>this.safety.mutation(async()=>{
          if(path==='/v1/runtime/release')return this.releaseRequest(buffered);
          if(!await this.released())return unavailable();
          await this.ensureReady();
          return this.scheduler!.run(()=>this.safety.run(async()=>{
            if(this.retryOnly){
              if(new URL(buffered.url).pathname!=='/v1/enroll')return unavailable();
              // Legacy unsealed state without a pending-effect marker only.
              // New failed effects keep their durable hold for manual reconciliation.
              const response=await this.api!(buffered);
              if(response.ok){await this.seal!();await this.verify!();this.retryOnly=false;}
              return response;
            }
            await this.verify!();
            try{return await this.api!(buffered);}finally{await this.seal!();}
          },45_000));
        }));
      }catch(e){
        if(e instanceof Error&&['request-too-large','request-timeout'].includes(e.message))
          return Response.json({error:e.message},{status:e.message==='request-too-large'?413:408,headers:{'cache-control':'no-store'}});
        return unavailable();
      }finally{this.pending--;}
    })();
    this.ctx.waitUntil(work);
    return await responseDeadline(work) as WorkerResponse;
  }
  override async alarm():Promise<void>{
    if(!this.config||this.safety.held||this.env.RUNTIME_MODE!=='active')return;
    await this.loadSafety();this.safety.check();
    await this.serial(()=>this.safety.mutation(async()=>{
      if(!await this.released())return;
      await this.ensureReady();if(!this.retryOnly)await this.scheduler!.alarm();
    }));
  }
}

export default {
  async fetch(request:Request,env:Env):Promise<Response>{
    const config=runtimeConfig(env);
    if(!config&&new URL(request.url).pathname==='/health'&&['GET','HEAD'].includes(request.method))
      return new Response(request.method==='HEAD'?null:JSON.stringify({phase:'archive-runtime',versionId:env.VERSION?.id??null,mode:'closed',release:null}),
        {headers:{'content-type':'application/json','cache-control':'no-store'}});
    if(!config||!allowed(request,config))return unavailable();
    try{
      const stub=env.LIBRARY.get(env.LIBRARY.idFromName(config.audience.libraryId));
      // Stream to the DO; it caps and cancels the body before admitting any write.
      // Avoid duplicate full-body buffers at gateway and object.
      return await responseDeadline(stub.fetch(request) as Promise<Response>);
    }catch(e){
      if(e instanceof Error&&['request-too-large','request-timeout'].includes(e.message))
        return Response.json({error:e.message},{status:e.message==='request-too-large'?413:408,headers:{'cache-control':'no-store'}});
      return unavailable();
    }
  },
};
